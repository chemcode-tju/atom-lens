const assert = require('node:assert/strict');
const {localName, open} = require('../plugin/web/import.js');
global.StructureParser = require('../plugin/web/parser.js');
global.StructureTrajectory = require('../plugin/web/trajectory-store.js');
global.StructureLammps = require('../plugin/web/lammps-metadata.js');
global.StructurePaired = require("../plugin/web/paired.js");
global.StructureMD = require('../plugin/web/md-stream.js');

(async () => {
  for (const name of ['POSCAR', 'CONTCAR', 'poscar.relaxed', 'sample.vasp']) assert.equal(localName(name), 'POSCAR');
  for (const name of ['XDATCAR', 'XDATCAR.1']) assert.equal(localName(name), 'XDATCAR');
  assert.equal(localName('sample.dump'), null);
  assert.equal(localName('unknown', 'gromacs'), null);
  assert.equal(localName('unknown', 'vasp'), 'POSCAR');
  const xyz = '1\n\nCu 1 2 3\n';
  const file = new File([xyz], 'sample.xyz');
  global.fetch = () => { throw Error('Local file must not be uploaded'); };
  const local = await open(file);
  assert.equal((await local.store.get(0)).frame.atoms[0].elem, 'Cu');
  const forcedXYZ=await open(new File([xyz],'unknown.structure'),{format:'extxyz'});
  assert.equal((await forcedXYZ.store.get(0)).frame.atoms[0].elem,'Cu');
  let request;
  global.StructureHostFiles={call:async args=>{request=args;return {text:xyz};}};
  const data = new File(['LAMMPS data\n1 atoms\n1 atom types\nMasses\n1 63.546 # Cu\nAtoms # atomic\n'], 'system.data');
  const imported = await open([data, new File(['units metal\nboundary p p f'], 'input.lammps')]);
  assert.equal(request.format,'lammps-data');
  assert.deepEqual(request.elements,['Cu']);
  assert.equal(request.atomStyle,'atomic');
  assert.ok(imported.note.includes('自动识别 Cu'));
  assert.equal(request.text,await data.text()); // Companion inputs never uploaded/executed.
  assert.equal(imported.store.count, 1);
  global.StructureHostFiles.call=async()=>{throw Error('ASE unavailable');};
  await assert.rejects(open(new File(['x'], 'x.pdb')), /ASE unavailable/);
  await assert.rejects(open([file,new File([xyz],'other.xyz')]),/一条轨迹/);
  await assert.rejects(open([file,new File(['units real'],'in.lammps')]),/不匹配/);
  const dump='ITEM: TIMESTEP\n0\nITEM: NUMBER OF ATOMS\n1\nITEM: BOX BOUNDS pp pp pp\n0 10\n0 10\n0 10\nITEM: ATOMS id type x y z\n1 1 1 2 3\n';
  global.fetch=()=>{throw Error('Dump and companion files must stay local');};
  const batch=await open([data,new File([dump],'trajectory.dump'),new File(['units metal'],'in.lammps')]);
  assert.equal(batch.name,'trajectory.dump');
  assert.equal((await batch.store.get(0)).frame.atoms[0].elem,'Cu');
  const forcedDump=await open([new File([dump],'misnamed.xyz'),data],{format:'lammps-dump-text'});
  assert.equal((await forcedDump.store.get(0)).frame.atoms[0].type,'1');
  await assert.rejects(open(new File([dump],'trajectory.dump')),/无法识别/);
  console.log('Import: local routing, backend conversion, element mapping and conversion errors passed.');
})().catch(error => { console.error(error); process.exitCode = 1; });
